-- ============================================================
-- Copie de test — étape A : EXPORTER LA STRUCTURE de la base réelle.
--
-- À exécuter dans le projet Supabase RÉEL (darwin), SQL Editor → New
-- query → coller ce texte → Run.
--
-- Ce script ne fait QUE LIRE : il ne modifie rien, et ne lit AUCUNE
-- donnée d'utilisateur (ni fiches, ni comptes, ni messages). Il décrit la
-- structure de la base (tables, colonnes, fonctions, règles de sécurité,
-- droits…) sous forme d'instructions SQL, plus les réglages communs de
-- l'appli (couleurs, textes : table dev_settings_public), pour pouvoir
-- construire une base de test identique (étape B :
-- 2-creer-la-base-de-test.sql).
--
-- Résultat : une seule ligne, une seule colonne « structure ». La copier
-- en entier (voir docs/COPIE-DE-TEST.md).
-- ============================================================
with
tbl as (
  select c.oid, c.relname
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
seqs as (
  select 10 as ord, format('create sequence if not exists public.%I;', s.sequencename) as stmt, s.sequencename as k
  from pg_sequences s
  where s.schemaname = 'public'
    and not exists (
      select 1 from pg_depend d join pg_class sc on sc.oid = d.objid
      where sc.relname = s.sequencename and d.deptype = 'i'
    )
),
tables as (
  select 20 as ord,
    format(E'create table if not exists public.%I (\n%s\n);', t.relname,
      string_agg(
        format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
          case when a.attidentity = 'a' then ' generated always as identity'
               when a.attidentity = 'd' then ' generated by default as identity' else '' end,
          case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
               when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
          case when a.attnotnull then ' not null' else '' end),
        E',\n' order by a.attnum)) as stmt,
    t.relname as k
  from tbl t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = t.oid and ad.adnum = a.attnum
  group by t.relname
),
cons as (
  select case when co.contype = 'f' then 60 else 30 end as ord,
    format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid)) as stmt,
    t.relname || '.' || co.conname as k
  from tbl t join pg_constraint co on co.conrelid = t.oid
  where co.contype in ('p', 'u', 'c', 'f', 'x')
),
idx as (
  select 35 as ord, regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX', 'CREATE \1INDEX IF NOT EXISTS') || ';' as stmt, ic.relname as k
  from tbl t join pg_index i on i.indrelid = t.oid join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
),
funcs as (
  select 40 as ord, pg_get_functiondef(p.oid) || ';' as stmt, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as k
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views as (
  select 50 as ord,
    format(E'create or replace view public.%I%s as\n%s', c.relname,
      case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
      pg_get_viewdef(c.oid, true)) as stmt,
    c.relname as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
trig as (
  select 70 as ord, pg_get_triggerdef(tg.oid) || ';' as stmt, c.relname || '.' || tg.tgname as k
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = tg.tgfoid join pg_namespace pn on pn.oid = p.pronamespace
  where not tg.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and pn.nspname = 'public'))
),
rls as (
  select 80 as ord,
    format('alter table public.%I enable row level security;', c.relname)
      || case when c.relforcerowsecurity then format(' alter table public.%I force row level security;', c.relname) else '' end as stmt,
    c.relname as k
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
),
pol as (
  select 85 as ord,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename,
      lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end) as stmt,
    p.tablename || '.' || p.policyname as k
  from pg_policies p where p.schemaname = 'public'
),
tgrants as (
  select 90 as ord,
    format('grant %s on public.%I to %s;', string_agg(g.privilege_type, ', ' order by g.privilege_type), g.table_name, g.grantee) as stmt,
    g.table_name || '.' || g.grantee as k
  from information_schema.role_table_grants g
  where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated', 'service_role')
  group by g.table_name, g.grantee
),
fgrants as (
  select 95 as ord,
    format('revoke all on function public.%I(%s) from public, anon, authenticated;%s', p.proname, pg_get_function_identity_arguments(p.oid),
      coalesce((
        select string_agg(format(' grant execute on function public.%I(%s) to %s;', p.proname, pg_get_function_identity_arguments(p.oid),
                 case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), '')
        from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
        left join pg_roles r on r.oid = a.grantee
        where a.privilege_type = 'EXECUTE' and (a.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))
      ), '')) as stmt,
    p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as k
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
pub as (
  select 97 as ord,
    format('do $pub$ begin alter publication supabase_realtime add table public.%I; exception when others then null; end $pub$;', pt.tablename) as stmt,
    pt.tablename as k
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
),
settings as (
  select 99 as ord,
    format('insert into public.dev_settings_public select * from json_populate_record(null::public.dev_settings_public, %L::json) on conflict do nothing;', (to_jsonb(d) - 'updated_by')::text) as stmt,
    'dev_settings_public' as k
  from public.dev_settings_public d
),
everything as (
  select * from seqs union all select * from tables union all select * from cons union all select * from idx
  union all select * from funcs union all select * from views union all select * from trig union all select * from rls
  union all select * from pol union all select * from tgrants union all select * from fgrants union all select * from pub
  union all select * from settings
)
select
  E'-- Structure exportée le ' || to_char(now(), 'YYYY-MM-DD HH24:MI') || E' (' || count(*) || E' instructions)\n'
  || E'set check_function_bodies = off;\n\n'
  || string_agg(
       case when ord in (30, 60, 70, 85)
         -- déjà présent (script relancé) : on passe
         then format(E'do $x$ begin\n%s\nexception when duplicate_object or duplicate_table or invalid_table_definition then null; end $x$;', stmt)
         else stmt end,
       E'\n\n' order by ord, k)
  || E'\n\nnotify pgrst, ''reload schema'';\n' as structure
from everything;
